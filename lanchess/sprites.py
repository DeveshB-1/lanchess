"""Block-art piece sprites for the big board sizes (pure data plus a pixel classifier).

Each sprite is a square bitmap, one string per pixel row, ``size`` pixels wide and tall. A board
square of a sprite size is ``size`` columns by ``size // 2`` rows: every terminal cell shows two
vertically stacked pixels with an upper-half block, and since a cell is about twice as tall as it
is wide the pixels come out square.

Pixel legend:

    .   transparent: the square colour shows through
    o   the piece's fill (light for White, very dark for Black)
    #   the piece's outline (dark for White, light grey for Black)
    x   a detail line inside the piece, drawn in the outline colour

The two biggest sizes are outlined drawings; the small ones are solid silhouettes with detail
lines, because a one-pixel outline would eat most of a tiny piece. Detail pixels are kept apart
from outline pixels so that a colour-less board can leave them blank inside a solid Black piece.
Every sprite keeps its bottom pixel row empty, so pieces on vertically adjacent squares never
touch.
"""

