SIZES: Tuple[int, ...] = tuple(sorted(ART))

_KINDS = {".": EMPTY, "o": FILL, "#": LINE, "x": DETAIL}
_CACHE: Dict[Tuple[int, str], Grid] = {}


def pixels(size: int, piece: str) -> Grid:
    """The pixel grid of ``piece`` (K, Q, R, B, N or P, either case) as EMPTY/FILL/LINE/DETAIL values."""
    key = (size, piece.upper())
    grid = _CACHE.get(key)
    if grid is None:
        grid = _CACHE[key] = tuple(tuple(_KINDS[char] for char in row) for row in ART[size][key[1]])
    return grid
